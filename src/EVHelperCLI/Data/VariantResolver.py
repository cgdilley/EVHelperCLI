def resolve_variants(top_set: TopSet) -> Iterable[TopSet]:
    db = Database.get_pokemon()
    for item in list(x for x in top_set.sets.items):
        if n := MEGA_STONES.get(item.item.name):
            match = db.showdown_name(n)
            if not match:
                continue
            if top_set.entry.pokemon.name.base_name() == match.name.base_name():
                yield TopSet(entry=UsageEntry(pokemon=match,
                                              rank=top_set.entry.rank,
                                              usage_percent=top_set.entry.usage_percent * item.percent,
                                              source=top_set.entry.source),
                             sets=CommonSets(pokemon=match,
                                             moves=top_set.sets.moves,
                                             items=[ItemUsage(item=item.item, percent=1)],
                                             abilities=[AbilityUsage(ability=match.abilities.primary, percent=1)],
                                             spreads=top_set.sets.spreads,
                                             natures=top_set.sets.natures))
                mult = 1 / (1 - item.percent) if item.percent != 1 else 0
                top_set.sets.items = [ItemUsage(item=x.item,
                                                percent=x.percent * mult)
                                      for x in top_set.sets.items if x.item.name != item.item.name]
                top_set.entry.usage_percent *= (1 - item.percent)
    yield top_set
